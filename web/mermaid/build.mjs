// Bundles the frame Mermaid draws in into internal/web/assets/app/mermaid/: frame.js (Mermaid with everything it loads,
// one classic script, minified) and LICENSES.txt with the licence text of every package in it. UnderDoc serves the page
// of the frame itself (internal/web, mermaidFrame), with a policy of its own. Nothing comes from a third party. The output
// depends only on the sources and the lockfile (scripts/build-js.sh).
//
//   node build.mjs --out <dir>
import { build } from 'esbuild';
import { readFileSync, writeFileSync, rmSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const at = process.argv.indexOf('--out');
const out = at > 0 ? resolve(process.argv[at + 1]) : join(here, '../../internal/web/assets/app/mermaid');
const lock = JSON.parse(readFileSync(join(here, 'package-lock.json'), 'utf8'));
// DOMPurify comes under MPL-2.0 or Apache-2.0; UnderDoc takes it under Apache-2.0.
const allowed = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'Unlicense', '(MPL-2.0 OR Apache-2.0)']);
// Packages whose package.json names no licence, with the one their licence file holds (checked below by its first line).
const unnamed = { khroma: ['MIT', /^The MIT License/] };

// Mermaid brings the ELK layout (elkjs, EPL-2.0 or GPL-3.0) and takes it by default. It is left out, as Mermaid's own tiny
// build does: its loaders are not registered, so a diagram that asks for ELK, or takes it by default, is laid out with
// dagre, which Mermaid falls back to. The build fails when the place moves with an update of Mermaid.
const withoutElk = {
  name: 'without-elk',
  setup(b) {
    b.onLoad({ filter: /mermaid[\\/]dist[\\/]chunks[\\/]mermaid\.core[\\/]chunk-[A-Z0-9]+\.mjs$/ }, (args) => {
      const source = readFileSync(args.path, 'utf8');
      if (!source.includes('registerDefaultLayoutLoaders')) return undefined;
      const call = '...elkLayoutLoaders()';
      const load = /import\("\.\/elk-[A-Z0-9]+\.mjs"\)/g;
      if (source.split(call).length !== 2 || (source.match(load) || []).length !== 1) {
        throw new Error(`${args.path}: the ELK layout loaders are not where they were`);
      }
      const contents = source.replace(call, '').replace(load, 'Promise.reject(new Error("The ELK layout is not part of UnderDoc."))');
      return { contents, loader: 'js' };
    });
    b.onResolve({ filter: /^elkjs(\/|$)/ }, (args) => {
      throw new Error(`elkjs is imported by ${args.importer}, but it is left out`);
    });
  },
};

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const result = await build({
  entryPoints: { frame: join(here, 'src/frame.js') },
  outdir: out,
  absWorkingDir: here,
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2022'],
  metafile: true,
  legalComments: 'none',
  charset: 'utf8',
  plugins: [withoutElk],
  logLevel: 'warning',
});

// The packages in the bundle, with the licence each ships.
const packages = new Map();
for (const info of Object.values(result.metafile.outputs)) {
  for (const input of Object.keys(info.inputs)) {
    const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/g);
    if (!match) continue;
    const key = match.join('/');
    const name = match[match.length - 1].replace(/^node_modules\//, '');
    const locked = lock.packages[key];
    if (!locked) throw new Error(`${key} is bundled but not in the lockfile`);
    if (locked.license === undefined && unnamed[name]) locked.license = unnamed[name][0];
    if (!allowed.has(locked.license)) throw new Error(`${name} ${locked.version} has the licence ${locked.license}, which is not allowed`);
    packages.set(name, { name, version: locked.version, license: locked.license, dir: join(here, key) });
  }
}
const sections = [...packages.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((p) => {
    const file = readdirSync(p.dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
    if (!file || !existsSync(join(p.dir, file))) throw new Error(`${p.name} ships no licence text`);
    const text = readFileSync(join(p.dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
    if (unnamed[p.name] && !unnamed[p.name][1].test(text)) throw new Error(`${p.name} ships a licence other than ${p.license}`);
    return `${p.name} ${p.version} (${p.license})\n${'-'.repeat(60)}\n${text}\n`;
  });
writeFileSync(
  join(out, 'LICENSES.txt'),
  'The diagrams of UnderDoc (frame.js) bundle these packages. Their licences follow.\n' +
    'Generated by web/mermaid/build.mjs from the lockfile; do not edit.\n\n' +
    sections.join('\n'),
);
console.log(`frame.js with ${packages.size} packages: ${[...packages.keys()].sort().join(', ')}`);
