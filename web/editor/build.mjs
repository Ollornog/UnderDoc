// Bundles the web editor into internal/web/assets/app/editor/: editor.js (one classic script, minified), editor.css and
// LICENSES.txt with the licence text of every package in the bundle. The output depends only on the sources and the
// lockfile, so the pipeline builds it again and compares (scripts/_js_check.sh).
//
//   npm ci --ignore-scripts && npm run build             into the assets
//   node build.mjs --out <dir>                           elsewhere, to compare
import { build } from 'esbuild';
import { readFileSync, writeFileSync, rmSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const at = process.argv.indexOf('--out');
const out = at > 0 ? resolve(process.argv[at + 1]) : join(here, '../../internal/web/assets/app/editor');
const lock = JSON.parse(readFileSync(join(here, 'package-lock.json'), 'utf8'));
const allowed = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD']);

// style-mod writes CodeMirror's base styles into a <style> element, which the CSP blocks; every import of it outside
// the stand-in goes to the stand-in, which hands it the document's adopted style sheets (src/style-mod-adopted.js).
const shim = join(here, 'src/style-mod-adopted.js');
const adoptedStyles = {
  name: 'adopted-styles',
  setup(b) {
    b.onResolve({ filter: /^style-mod$/ }, (args) => (args.importer === shim ? undefined : { path: shim }));
  },
};

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const result = await build({
  entryPoints: { editor: join(here, 'src/editor.js') },
  outdir: out,
  absWorkingDir: here,
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2022'],
  metafile: true,
  legalComments: 'none',
  charset: 'utf8',
  plugins: [adoptedStyles],
  logLevel: 'warning',
});

// The packages in the bundle, with the licence each ships.
const packages = new Map();
for (const info of Object.values(result.metafile.outputs)) {
  for (const input of Object.keys(info.inputs)) {
    const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/g);
    if (!match) continue;
    const key = match.join('/');
    const name = match[match.length - 1].replace(/^node_modules\//, '');
    const locked = lock.packages[key];
    if (!locked) throw new Error(`${key} is bundled but not in the lockfile`);
    if (!allowed.has(locked.license)) throw new Error(`${name} ${locked.version} has the licence ${locked.license}, which is not allowed`);
    packages.set(name, { name, version: locked.version, license: locked.license, dir: join(here, key) });
  }
}
const sections = [...packages.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((p) => {
    const file = readdirSync(p.dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
    if (!file || !existsSync(join(p.dir, file))) throw new Error(`${p.name} ships no licence text`);
    const text = readFileSync(join(p.dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
    return `${p.name} ${p.version} (${p.license})\n${'-'.repeat(60)}\n${text}\n`;
  });
writeFileSync(
  join(out, 'LICENSES.txt'),
  'The web editor of UnderDoc (editor.js, editor.css) bundles these packages. Their licences follow.\n' +
    'Generated by web/editor/build.mjs from the lockfile; do not edit.\n\n' +
    sections.join('\n'),
);
console.log(`editor.js and editor.css with ${packages.size} packages: ${[...packages.keys()].sort().join(', ')}`);
