// Puts the PDF preview into internal/web/assets/app/pdfjs/: pdf.js as it ships (pdf.min.mjs, its worker, the fonts,
// character maps and decoders it loads when a PDF needs them), the small viewer of UnderDoc (src/viewer.mjs) and
// LICENSES.txt. Everything is served by UnderDoc itself; nothing comes from a third party. The output depends only on the
// sources and the lockfile (scripts/build-js.sh).
//
//   node build.mjs --out <dir>
import { readFileSync, writeFileSync, rmSync, mkdirSync, cpSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const at = process.argv.indexOf('--out');
const out = at > 0 ? resolve(process.argv[at + 1]) : join(here, '../../internal/web/assets/app/pdfjs');
const lock = JSON.parse(readFileSync(join(here, 'package-lock.json'), 'utf8'));
const dist = join(here, 'node_modules/pdfjs-dist');
const locked = lock.packages['node_modules/pdfjs-dist'];
if (!locked) throw new Error('pdfjs-dist is not in the lockfile');
if (locked.license !== 'Apache-2.0') throw new Error(`pdfjs-dist has the licence ${locked.license}, which is not allowed`);
const shipped = JSON.parse(readFileSync(join(dist, 'package.json'), 'utf8'));
if (shipped.version !== locked.version) throw new Error(`pdfjs-dist ${shipped.version} is installed, the lockfile names ${locked.version}`);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const file of ['build/pdf.min.mjs', 'build/pdf.worker.min.mjs']) cpSync(join(dist, file), join(out, file.split('/').pop()));
for (const dir of ['standard_fonts', 'cmaps', 'wasm', 'iccs']) cpSync(join(dist, dir), join(out, dir), { recursive: true });
cpSync(join(here, 'src/viewer.mjs'), join(out, 'viewer.mjs'));

const notices = [['pdf.js', join(dist, 'LICENSE')]];
for (const dir of ['standard_fonts', 'wasm']) {
  for (const f of readdirSync(join(dist, dir)).filter((f) => f.startsWith('LICENSE')).sort()) notices.push([`${dir}/${f}`, join(dist, dir, f)]);
}
writeFileSync(
  join(out, 'LICENSES.txt'),
  `The PDF preview of UnderDoc ships pdfjs-dist ${locked.version} (Apache-2.0) with the fonts and decoders it brings.\n` +
    'Their licences follow. Generated by web/pdfjs/build.mjs from the lockfile; do not edit.\n\n' +
    notices.map(([name, file]) => `${name}\n${'-'.repeat(60)}\n${readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()}\n`).join('\n'),
);
console.log(`pdf.js ${locked.version} with its fonts, character maps and decoders`);
